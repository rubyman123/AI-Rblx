"""Office Floor 14: generated images. Map tool for MapKit by fwjelaa.

    python maps/office-floor-14/images.py [--no-upload] [--only name,name]

- ofc_sky: an overcast storm night over a city: clouds lit orange from below by sodium light pollution, near
  black at the zenith. Sampled in 3D direction space, so the six faces meet without seams (face orientation from
  kit/tools/sky.py, measured in Studio). 512 px faces (1024 never render).
- ofc_facade_*: night facades for the skyline (lit and dark windows), shown on SurfaceGuis with LightInfluence 0.
- ofc_rain_glass: droplets and runs on a window (alpha), a Texture that slides down the glass.
- ofc_stain_*: water stain on ceiling tiles, a drip streak on a wall, a dark patch on carpet (alpha decals).
Everything is generated here (CC0). Uploads go to the key's user and are recorded in assets.json."""
import argparse
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

PACK = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(PACK / "kit" / "tools"))

import keyfile  # noqa: E402

OUT = PACK / "cache" / "images"
SOURCE = "generated by maps/office-floor-14/images.py"

FACES = {
    "Ft": lambda u, v: (2 * u - 1, 1 - 2 * v, -np.ones_like(u)),
    "Rt": lambda u, v: (-np.ones_like(u), 1 - 2 * v, 1 - 2 * u),
    "Bk": lambda u, v: (1 - 2 * u, 1 - 2 * v, np.ones_like(u)),
    "Lf": lambda u, v: (np.ones_like(u), 1 - 2 * v, 2 * u - 1),
    "Up": lambda u, v: (1 - 2 * v, np.ones_like(u), 1 - 2 * u),
    "Dn": lambda u, v: (2 * v - 1, -np.ones_like(u), 1 - 2 * u),
}


# ---------- noise ----------

class ValueNoise3:
    def __init__(self, seed, size=64):
        self.g = np.random.default_rng(seed).random((size, size, size))
        self.n = size

    def __call__(self, x, y, z):
        n = self.n
        xi, yi, zi = np.floor(x).astype(int), np.floor(y).astype(int), np.floor(z).astype(int)
        xf, yf, zf = x - xi, y - yi, z - zi
        s = lambda t: t * t * (3 - 2 * t)  # noqa: E731
        u, v, w = s(xf), s(yf), s(zf)
        out = 0
        for dx in (0, 1):
            for dy in (0, 1):
                for dz in (0, 1):
                    c = self.g[(xi + dx) % n, (yi + dy) % n, (zi + dz) % n]
                    out = out + c * (u if dx else 1 - u) * (v if dy else 1 - v) * (w if dz else 1 - w)
        return out


def fbm(noise, x, y, z, octaves=6, lac=2.0, gain=0.5):
    total, amp, freq, norm = 0, 1.0, 1.0, 0
    for _ in range(octaves):
        total = total + amp * noise(x * freq, y * freq, z * freq)
        norm += amp
        amp *= gain
        freq *= lac
    return total / norm


def smooth(a, b, x):
    t = np.clip((x - a) / (b - a), 0, 1)
    return t * t * (3 - 2 * t)


# ---------- sky ----------

def sky_faces(size=512, seed=14):
    noise = ValueNoise3(seed)
    warp = ValueNoise3(seed + 1)
    faces = {}
    px = (np.arange(size) + 0.5) / size
    u, v = np.meshgrid(px, px)
    for name, fn in FACES.items():
        dx, dy, dz = fn(u, v)
        L = np.sqrt(dx * dx + dy * dy + dz * dz)
        dx, dy, dz = dx / L, dy / L, dz / L
        el = np.arcsin(np.clip(dy, -1, 1))  # elevation
        # clouds: a low deck seen in perspective, stretched near the horizon
        k = 1.0 / np.maximum(dy + 0.12, 0.05)
        cx, cz = dx * k * 1.6, dz * k * 1.6
        w = fbm(warp, cx * 0.7 + 3.1, 7.7, cz * 0.7, 4)
        c = fbm(noise, cx + 2.5 * w, 1.3, cz + 2.5 * w, 6)
        dens = smooth(0.35, 0.75, c)
        # light pollution: warm glow pooled at the horizon, more toward the city centre (north-east)
        bear = np.arctan2(dx, -dz)
        city = 0.75 + 0.25 * np.cos(bear - np.radians(35))
        glow = np.exp(-np.maximum(el, 0) / np.radians(14)) * city
        zen = np.array([9, 10, 14]) / 255
        warm = np.array([96, 66, 46]) / 255
        dull = np.array([38, 36, 42]) / 255
        base = zen + (dull - zen) * np.exp(-np.maximum(el, 0) / np.radians(40))[..., None]
        base = base + (warm - dull) * (glow ** 1.3)[..., None] * 0.9
        # cloud undersides catch the glow; thin parts are darker gaps
        cloud = base * (0.55 + 0.75 * dens)[..., None] + (np.array([30, 20, 14]) / 255) * (dens * glow)[..., None]
        # below the horizon: haze over the city, slightly brighter right at the horizon
        below = np.array([34, 27, 24]) / 255 * (0.6 + 0.6 * np.exp(el / np.radians(6)))[..., None]
        img = np.where((el >= 0)[..., None], cloud, below)
        img = img * (1 + np.random.default_rng(seed + hash(name) % 97).normal(0, 0.012, img.shape))  # film grain vs banding
        faces[name] = Image.fromarray((np.clip(img, 0, 1) * 255).astype(np.uint8), "RGB")
    return faces


# ---------- facades ----------

def facade(seed, cols, rows, frame_rgb, glass_rgb, lit_colors, lit_ratio, size=512, mullion=2, slab=4):
    rng = np.random.default_rng(seed)
    img = Image.new("RGB", (size, size), frame_rgb)
    d = ImageDraw.Draw(img)
    cw, rh = size / cols, size / rows
    for r in range(rows):
        floor_lit = rng.random() < 0.35  # whole floors tend to be on or off together
        for c in range(cols):
            x0, y0 = int(c * cw + mullion), int(r * rh + slab)
            x1, y1 = int((c + 1) * cw - mullion), int((r + 1) * rh - 1)
            p = lit_ratio * (2.2 if floor_lit else 0.5)
            if rng.random() < p:
                col = np.array(lit_colors[rng.integers(0, len(lit_colors))], float) * rng.uniform(0.6, 1.0)
                d.rectangle([x0, y0, x1, y1], fill=tuple(col.astype(int)))
                if rng.random() < 0.4:  # half-drawn blinds
                    stop = y0 + int((y1 - y0) * rng.uniform(0.2, 0.8))
                    for yy in range(y0, stop, 2):
                        d.line([x0, yy, x1, yy], fill=tuple((col * 0.55).astype(int)))
            else:
                g = np.array(glass_rgb, float) * rng.uniform(0.7, 1.15)
                d.rectangle([x0, y0, x1, y1], fill=tuple(g.astype(int)))
    return img.filter(ImageFilter.GaussianBlur(0.6))


def facades():
    fluo = [(220, 228, 235), (200, 215, 225), (235, 230, 205)]
    warm = [(255, 200, 130), (240, 180, 110), (255, 220, 160)]
    return {
        "ofc_facade_office": facade(1, 16, 24, (26, 27, 30), (14, 17, 24), fluo, 0.12),
        "ofc_facade_glass": facade(2, 24, 32, (18, 22, 28), (10, 14, 22), fluo + [(160, 190, 220)], 0.07, mullion=1, slab=2),
        "ofc_facade_resi": facade(3, 10, 16, (40, 34, 30), (16, 15, 16), warm, 0.18, mullion=4, slab=6),
    }


# ---------- rain on glass ----------

def rain_glass(size=512, seed=9):
    rng = np.random.default_rng(seed)
    big = size * 2
    rgba = np.zeros((big, big, 4), np.float32)
    yy, xx = np.mgrid[0:big, 0:big]

    def drop(cx, cy, r, alpha):
        x0, x1 = int(max(cx - r - 2, 0)), int(min(cx + r + 3, big))
        y0, y1 = int(max(cy - r - 2, 0)), int(min(cy + r + 3, big))
        if x1 <= x0 or y1 <= y0:
            return
        sx, sy = xx[y0:y1, x0:x1] - cx, (yy[y0:y1, x0:x1] - cy) * 1.15
        dist = np.sqrt(sx * sx + sy * sy) / r
        inside = dist < 1
        rim = np.clip((dist - 0.6) / 0.4, 0, 1) * inside
        hi = np.exp(-(((sx + r * 0.35) ** 2 + (sy + r * 0.35) ** 2) / (0.08 * r * r + 1)))  # specular dot
        a = inside * alpha * (0.25 + 0.75 * rim) + hi * alpha * 0.9 * inside
        col = 0.55 + 0.45 * hi
        reg = rgba[y0:y1, x0:x1]
        reg[..., 3] = np.maximum(reg[..., 3], a)
        for ch in range(3):
            reg[..., ch] = np.maximum(reg[..., ch], col * inside)

    for _ in range(1400):  # fine mist of droplets
        drop(rng.uniform(0, big), rng.uniform(0, big), rng.uniform(1.5, 4.5), rng.uniform(0.35, 0.7))
    for _ in range(90):  # bigger beads
        drop(rng.uniform(0, big), rng.uniform(0, big), rng.uniform(5, 11), rng.uniform(0.5, 0.8))
    for _ in range(26):  # runs: a bead with a wobbling trail behind it
        x = rng.uniform(0, big)
        y = rng.uniform(0, big)
        length = rng.uniform(80, 400)
        for s in np.arange(0, length, 2.0):
            wob = 3 * np.sin(s / rng.uniform(15, 30))
            drop((x + wob) % big, (y - s) % big, rng.uniform(1.2, 2.2), 0.45)
        drop(x % big, y % big, rng.uniform(6, 9), 0.85)
    img = Image.fromarray((np.clip(rgba, 0, 1) * 255).astype(np.uint8), "RGBA").resize((size, size), Image.LANCZOS)
    return img


# ---------- stains ----------

def stain(seed, kind, size=512):
    rng = np.random.default_rng(seed)
    noise = ValueNoise3(seed, 32)
    yy, xx = (np.mgrid[0:size, 0:size] + 0.5) / size
    n = fbm(noise, xx * 6, yy * 6, 0.5, 5)
    if kind == "ring":  # water stain on ceiling tiles: a pale bloom with a dark tide line
        r = np.sqrt((xx - 0.5) ** 2 + (yy - 0.5) ** 2) * 2 + (n - 0.5) * 0.45
        edge = np.exp(-((r - 0.78) / 0.035) ** 2)
        fill = smooth(0.85, 0.3, r) * 0.35
        a = np.clip(edge * 0.85 + fill + (n - 0.5) * 0.1, 0, 1) * smooth(1.0, 0.85, r)
        rgb = np.stack([0.42 + 0 * n, 0.32 + 0 * n, 0.2 + 0 * n], -1)
    elif kind == "drip":  # streaks running down a wall from a leak
        a = np.zeros((size, size))
        for _ in range(9):
            x = rng.uniform(0.2, 0.8)
            w = rng.uniform(0.006, 0.02)
            ln = rng.uniform(0.4, 0.95)
            a += np.exp(-((xx - x - 0.01 * np.sin(yy * 20)) / w) ** 2) * smooth(ln, ln - 0.25, yy) * rng.uniform(0.3, 0.8)
        a += smooth(0.3, 0.0, yy) * smooth(0.55, 0.1, np.abs(xx - 0.5)) * 0.6
        a = np.clip(a * (0.7 + 0.6 * n), 0, 0.85)
        rgb = np.stack([0.24 + 0 * n, 0.2 + 0 * n, 0.15 + 0 * n], -1)
    else:  # dark patch soaked into carpet
        r = np.sqrt((xx - 0.5) ** 2 + (yy - 0.5) ** 2) * 2 + (n - 0.5) * 0.7
        a = np.clip(smooth(0.95, 0.35, r) * 0.8 + (n - 0.5) * 0.15, 0, 0.85)
        rgb = np.stack([0.12 + 0 * n, 0.08 + 0 * n, 0.07 + 0 * n], -1)
    rgba = np.concatenate([rgb, a[..., None]], -1)
    return Image.fromarray((np.clip(rgba, 0, 1) * 255).astype(np.uint8), "RGBA")


# ---------- particles and screens ----------

def rain_streak(w=32, h=256):
    # one falling drop smeared by motion blur: a soft vertical line, brightest in the middle (alpha)
    x = (np.arange(w) + 0.5) / w - 0.5
    y = (np.arange(h) + 0.5) / h
    a = np.exp(-(x[None, :] / 0.12) ** 2) * np.sin(np.pi * y[:, None]) ** 0.6
    rgba = np.zeros((h, w, 4))
    rgba[..., :3] = 0.85
    rgba[..., 3] = a * 0.9
    return Image.fromarray((rgba * 255).astype(np.uint8), "RGBA")


def tv_static(size=256, seed=5):
    # analogue snow with faint horizontal banding (a CRT with no signal)
    rng = np.random.default_rng(seed)
    n = rng.random((size, size))
    band = 0.85 + 0.15 * np.sin(np.linspace(0, 14 * np.pi, size))[:, None]
    g = np.clip(n * band, 0, 1)
    return Image.fromarray((np.stack([g * 0.92, g * 0.95, g], -1) * 255).astype(np.uint8), "RGB")


# ---------- upload ----------

def upload_image(path, label):
    import upload
    from run import introspect

    key = keyfile.find_key()
    if not key:
        return None
    return upload.upload_file(path, "Image", label, key, introspect(key)["authorizedUserId"])


def record(section, name, entry):
    import manifest
    manifest.update(PACK / "assets.json", lambda data: data.setdefault(section, {}).__setitem__(name, entry))


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-upload", action="store_true")
    ap.add_argument("--only", default="")
    a = ap.parse_args(argv)
    only = set(filter(None, a.only.split(",")))
    OUT.mkdir(parents=True, exist_ok=True)

    if not only or "ofc_sky" in only:
        ids = {}
        for face, img in sky_faces().items():
            p = OUT / f"ofc_sky_{face}.png"
            img.save(p)
            if not a.no_upload:
                ids[face] = upload_image(p, f"ofc_sky {face}")
        print("ofc_sky:", ids or "written")
        if ids:
            record("skies", "ofc_sky", {"ids": ids, "source": SOURCE, "license": "CC0 1.0",
                                        "remake": "python maps/office-floor-14/images.py --only ofc_sky"})

    singles = dict(facades())
    singles["ofc_rain_glass"] = rain_glass()
    singles["ofc_stain_ring"] = stain(1, "ring")
    singles["ofc_stain_drip"] = stain(2, "drip")
    singles["ofc_stain_floor"] = stain(3, "patch")
    singles["ofc_rain_streak"] = rain_streak()
    singles["ofc_static"] = tv_static()
    for name, img in singles.items():
        if only and name not in only:
            continue
        p = OUT / f"{name}.png"
        img.save(p)
        if a.no_upload:
            print(name, "written")
            continue
        iid = upload_image(p, name)
        record("images", name, {"id": iid, "source": SOURCE, "license": "CC0 1.0",
                                "remake": "python maps/office-floor-14/images.py --only " + name})
        print(name, iid)


if __name__ == "__main__":
    main(sys.argv[1:])
