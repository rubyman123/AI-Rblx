"""Office Floor 14: generated sound design (no music, no licence questions). Map tool for MapKit by fwjelaa.

    python maps/office-floor-14/sounds.py [--no-upload] [--only name,name]

Writes cache/audio/ofc_*.wav, uploads each as Audio with the pack's key and records it in assets.json `sounds`.
Loops are made periodic (frequency-domain noise, whole-cycle envelopes, wrapped events) so they never click.
One-shots share ONE file, `ofc_sfx`, to stay inside Roblox's monthly audio upload quota: assets.json records
every one-shot's [start, end] seconds under `regions`, and the map plays them with Sound.PlaybackRegion."""
import argparse
import sys
import wave
from pathlib import Path

import numpy as np
from scipy import signal

PACK = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(PACK / "kit" / "tools"))

import keyfile  # noqa: E402

RATE = 44100
OUT = PACK / "cache" / "audio"
SOURCE = "generated by maps/office-floor-14/sounds.py"


# ---------- building blocks ----------

def secs(s):
    return int(round(s * RATE))


def norm(x, peak=0.9):
    m = np.max(np.abs(x))
    return x if m == 0 else x / m * peak


def periodic_noise(rng, n, lo, hi, tilt=0.0):
    # noise built over exactly n samples in the frequency domain: periodic in n, so a loop has no seam
    f = np.fft.rfftfreq(n, 1 / RATE)
    mag = np.where((f >= lo) & (f <= hi), 1.0 / np.maximum(f, 1.0) ** tilt, 0.0)
    x = np.fft.irfft(mag * np.exp(1j * rng.uniform(0, 2 * np.pi, len(f))), n)
    return x / (np.max(np.abs(x)) + 1e-12)


def band(x, lo=None, hi=None, order=4):
    if lo and hi:
        sos = signal.butter(order, [lo, hi], btype="band", fs=RATE, output="sos")
    elif lo:
        sos = signal.butter(order, lo, btype="high", fs=RATE, output="sos")
    else:
        sos = signal.butter(order, hi, btype="low", fs=RATE, output="sos")
    return signal.sosfilt(sos, x)


def noise(rng, n):
    return rng.normal(0, 1, n)


def env_exp(n, tau, attack=0.002):
    t = np.arange(n) / RATE
    a = np.clip(t / max(attack, 1e-4), 0, 1)
    return a * np.exp(-t / tau)


def resonator(n, freq, tau, phase=0.0):
    t = np.arange(n) / RATE
    return np.sin(2 * np.pi * freq * t + phase) * np.exp(-t / tau)


def room(x, rng, rt=0.6, wet=0.25, lo=200, hi=6000):
    # cheap convolution reverb: an exponentially decaying, band-limited noise impulse response
    n = secs(rt * 1.6)
    ir = band(noise(rng, n), lo, hi, 2) * np.exp(-np.arange(n) / RATE / (rt / 6.9))
    ir /= np.sqrt(np.sum(ir ** 2)) + 1e-12
    tail = np.zeros(len(x) + n)
    conv = signal.fftconvolve(x, ir)
    tail[: len(conv)] = conv[: len(tail)]
    out = np.zeros(len(x) + n)
    out[: len(x)] += x
    return out + wet * tail * (np.max(np.abs(x)) / (np.max(np.abs(tail)) + 1e-12))


def place(buf, event, at, wrap=False):
    n = len(buf)
    if wrap:
        idx = (np.arange(len(event)) + at) % n
        np.add.at(buf, idx, event)
    else:
        end = min(n, at + len(event))
        buf[at:end] += event[: end - at]


def write(name, x):
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / f"{name}.wav"
    pcm = (np.clip(x, -1, 1) * 32767).astype("<i2")
    with wave.open(str(path), "wb") as f:
        f.setnchannels(1)
        f.setsampwidth(2)
        f.setframerate(RATE)
        f.writeframes(pcm.tobytes())
    return path


# ---------- loops ----------

def rain_loop(seconds=30.0, seed=11):
    # heavy rain on a curtain wall, heard from inside: a broad wash, dense glass ticks, runoff drips, wind gusts
    rng = np.random.default_rng(seed)
    n = secs(seconds)
    t = np.arange(n) / n
    gust = 0.75 + 0.12 * np.sin(2 * np.pi * 3 * t + 1.0) + 0.08 * np.sin(2 * np.pi * 7 * t + 0.3) + 0.05 * np.sin(2 * np.pi * 13 * t)
    wash = periodic_noise(rng, n, 150, 9000, 0.55)
    hiss = periodic_noise(rng, n, 2500, 12000, 0.2)
    wind = periodic_noise(rng, n, 25, 220, 1.1)
    x = 0.55 * wash * gust + 0.12 * hiss * gust ** 2 + 0.35 * wind * (gust - 0.55)
    ticks = np.zeros(n)
    for _ in range(int(seconds * 260)):  # drops hitting glass
        L = secs(rng.uniform(0.004, 0.018))
        f = rng.uniform(1800, 6500)
        ev = resonator(L, f, rng.uniform(0.0015, 0.005)) + 0.6 * noise(rng, L) * env_exp(L, 0.002)
        place(ticks, ev * rng.uniform(0.05, 0.35) ** 1.5, rng.integers(0, n), wrap=True)
    drips = np.zeros(n)
    for _ in range(int(seconds * 3)):  # fat drops from the frame above, louder, lower
        L = secs(0.06)
        ev = resonator(L, rng.uniform(500, 1400), 0.012) * rng.uniform(0.2, 0.6)
        place(drips, ev, rng.integers(0, n), wrap=True)
    x = x + 0.9 * band(ticks, 900, 9000, 2) + 0.4 * drips
    return norm(x, 0.8)


def hvac_loop(seconds=20.0, seed=5):
    # the building breathing at night: low duct rumble, a soft airflow hiss, a faint 60 Hz electrical bed
    rng = np.random.default_rng(seed)
    n = secs(seconds)
    t = np.arange(n) / n
    swell = 0.8 + 0.1 * np.sin(2 * np.pi * 2 * t + 0.4) + 0.1 * np.sin(2 * np.pi * 5 * t + 2.0)
    rumble = periodic_noise(rng, n, 18, 180, 1.4)
    air = periodic_noise(rng, n, 250, 2500, 0.8)
    tt = np.arange(n) / RATE
    mains = 0.05 * np.sin(2 * np.pi * 60 * tt) + 0.03 * np.sin(2 * np.pi * 120 * tt)  # 20 s = whole cycles
    return norm(0.8 * rumble * swell + 0.25 * air * swell + mains, 0.7)


def server_loop(seconds=16.0, seed=21):
    # a rack room: dozens of fans (blade tones that beat against each other), hiss, and disk heads seeking
    rng = np.random.default_rng(seed)
    n = secs(seconds)
    tt = np.arange(n) / RATE
    x = 0.55 * periodic_noise(rng, n, 120, 9000, 0.35) + 0.4 * periodic_noise(rng, n, 30, 300, 1.0)
    for _ in range(9):  # fan blade-pass tones: whole cycles in the loop so they stay seamless
        f = round(rng.uniform(140, 420) * seconds) / seconds
        x += rng.uniform(0.02, 0.06) * (np.sin(2 * np.pi * f * tt) + 0.4 * np.sin(2 * np.pi * 2 * f * tt + 1.0))
    clicks = np.zeros(n)
    for _ in range(int(seconds * 5)):
        L = secs(0.01)
        place(clicks, resonator(L, rng.uniform(2500, 4500), 0.0015) * rng.uniform(0.1, 0.3), rng.integers(0, n), wrap=True)
    return norm(x + clicks, 0.75)


def vending_loop(seconds=12.0, seed=8):
    # an old vending machine: compressor hum with harmonics, a loose-panel rattle, a backlight ballast buzz
    rng = np.random.default_rng(seed)
    n = secs(seconds)
    tt = np.arange(n) / RATE
    w = 2 * np.pi * 50 * tt  # 12 s holds whole cycles of 50 Hz
    hum = np.sin(w) + 0.5 * np.sin(2 * w) + 0.35 * np.sin(3 * w + 0.5) + 0.2 * np.sign(np.sin(2 * w)) * 0.5
    rattle = periodic_noise(rng, n, 300, 1600, 0.3) * (0.5 + 0.5 * np.sin(2 * np.pi * 25 * tt) ** 8)
    buzz = 0.15 * np.sign(np.sin(2 * np.pi * 120 * tt))
    bed = periodic_noise(rng, n, 40, 400, 1.0)
    return norm(0.6 * hum + 0.12 * rattle + 0.06 * buzz + 0.25 * bed, 0.7)


def hum_loop(seconds=8.0, base=120.0):
    # fluorescent ballast: twice mains frequency plus harmonics and a magnetic buzz; whole cycles, seamless
    cycles = max(1, round(seconds * base))
    n = int(round(cycles / base * RATE))
    w = 2 * np.pi * base * np.arange(n) / RATE
    x = 0.5 * np.sin(w) + 0.25 * np.sin(2 * w) + 0.12 * np.sin(3 * w) + 0.07 * np.sin(5 * w)
    x += 0.05 * np.sign(np.sin(w)) + 0.02 * np.sign(np.sin(4 * w))
    x += np.random.default_rng(1).normal(0, 0.008, n)
    return norm(x, 0.6)


# ---------- one-shots ----------

def thunder(seed, crack=True, length=7.0, distance=1.0):
    rng = np.random.default_rng(seed)
    n = secs(length)
    x = np.zeros(n)
    start = secs(0.05 if crack else 0.3)
    if crack:  # the near strike: a ripping crack, then the sky tearing
        L = secs(0.9)
        rip = band(noise(rng, L), 600, 9000, 2) * env_exp(L, 0.12, 0.004)
        for _ in range(30):
            at = rng.integers(0, secs(0.5))
            l2 = secs(0.02)
            place(rip, band(noise(rng, l2), 1500, 9000, 2) * env_exp(l2, 0.006) * rng.uniform(0.5, 2.0), at)
        place(x, rip * 0.9, start)
    # rolling rumble: overlapping swells of low noise, each with its own body
    body = np.zeros(n)
    t = start
    while t < n - secs(1.0):
        L = secs(rng.uniform(1.0, 2.6))
        e = np.sin(np.linspace(0, np.pi, L)) ** rng.uniform(1.5, 3.0)
        place(body, band(noise(rng, L), 20, 260 / distance, 2) * e * rng.uniform(0.5, 1.0), t)
        t += secs(rng.uniform(0.25, 0.8))
    decay = np.exp(-np.arange(n) / RATE / (length * 0.38))
    x += 1.4 * body * decay
    x += 0.25 * band(noise(rng, n), 200, 900 / distance, 2) * decay ** 2
    return norm(band(x, 18, None, 2) if not crack else x, 0.95)


def phone_ring(seed=3):
    # a desk phone's electronic ring: two tones trilling at 20 Hz through a small speaker, 1.6 s burst
    rng = np.random.default_rng(seed)
    n = secs(2.0)
    tt = np.arange(n) / RATE
    trill = (np.sin(2 * np.pi * 20 * tt) > 0).astype(float)
    tone = trill * np.sin(2 * np.pi * 1180 * tt) + (1 - trill) * np.sin(2 * np.pi * 1520 * tt)
    tone = np.tanh(2.5 * tone)  # small speaker breaking up
    gate = np.clip(tt / 0.01, 0, 1) * np.clip((1.6 - tt) / 0.02, 0, 1)
    x = band(tone * gate, 450, 5000, 2) + 0.004 * noise(rng, n)
    return norm(room(x, rng, rt=0.9, wet=0.35), 0.85)


def bell(freq, seed=1, length=2.6):
    rng = np.random.default_rng(seed)
    n = secs(length)
    x = np.zeros(n)
    for ratio, amp, tau in [(1.0, 1.0, 1.1), (2.0, 0.45, 0.7), (2.76, 0.3, 0.45), (5.4, 0.12, 0.2), (8.93, 0.05, 0.1)]:
        x += amp * resonator(n, freq * ratio, tau, rng.uniform(0, 6.28))
    return x * np.clip(np.arange(n) / secs(0.003), 0, 1)


def elevator_ding():
    rng = np.random.default_rng(31)
    x = bell(784, 2, 2.6)  # G5
    return norm(room(x, rng, rt=1.2, wet=0.3), 0.8)


def elevator_doors():
    # doors rolling open: motor whine, wheels on the track, a soft clunk at the stop
    rng = np.random.default_rng(32)
    n = secs(3.4)
    tt = np.arange(n) / RATE
    run = np.clip(tt / 0.3, 0, 1) * np.clip((2.6 - tt) / 0.4, 0, 1)
    f = 220 + 60 * np.clip(tt / 1.3, 0, 1)
    whine = np.sin(2 * np.pi * np.cumsum(f) / RATE) * 0.15
    rumble = band(noise(rng, n), 60, 500, 2) * 0.6
    x = (whine + rumble) * run
    L = secs(0.4)
    place(x, (resonator(L, 95, 0.08) + 0.4 * band(noise(rng, L), 200, 2000, 2) * env_exp(L, 0.03)) * 1.2, secs(2.6))
    return norm(room(x, rng, rt=1.0, wet=0.3), 0.8)


def door_slam():
    rng = np.random.default_rng(41)
    n = secs(0.8)
    thump = resonator(n, 70, 0.09) + 0.6 * resonator(n, 140, 0.05, 1.0)
    crack = band(noise(rng, n), 300, 4000, 2) * env_exp(n, 0.025, 0.001)
    latch = np.zeros(n)
    place(latch, resonator(secs(0.05), 2600, 0.008) * 0.5, secs(0.03))
    x = 1.2 * thump + 0.8 * crack + latch
    return norm(room(x, rng, rt=1.6, wet=0.5, lo=80, hi=3000), 0.9)


def knock_set():
    # three knocks on a hollow office door, the third one harder
    rng = np.random.default_rng(42)
    n = secs(1.6)
    x = np.zeros(n)
    for i, (at, amp) in enumerate([(0.0, 0.7), (0.32, 0.75), (0.62, 1.0)]):
        L = secs(0.2)
        k = resonator(L, 180 + rng.uniform(-8, 8), 0.035) + 0.5 * resonator(L, 720, 0.012) \
            + 0.4 * band(noise(rng, L), 800, 5000, 2) * env_exp(L, 0.004)
        place(x, k * amp, secs(at))
    return norm(room(x, rng, rt=1.1, wet=0.4, lo=100, hi=3000), 0.85)


def footsteps_distant():
    # someone walking slowly across a hard floor in another room: heels, low-passed by the walls
    rng = np.random.default_rng(51)
    n = secs(6.0)
    x = np.zeros(n)
    t = 0.2
    for i in range(9):
        L = secs(0.25)
        heel = resonator(L, rng.uniform(110, 140), 0.03) + 0.5 * band(noise(rng, L), 500, 3500, 2) * env_exp(L, 0.012)
        place(x, heel * rng.uniform(0.7, 1.0) * (0.6 + 0.4 * np.sin(i / 8 * np.pi)), secs(t))
        t += rng.uniform(0.6, 0.7)
    x = band(x, None, 1800, 2)
    return norm(room(x, rng, rt=1.4, wet=0.6, lo=80, hi=2000), 0.8)


def printer_run():
    # a laser printer waking by itself: fuser fan spin-up, rollers, paper feed clacks, a page out, settle
    rng = np.random.default_rng(61)
    n = secs(7.5)
    tt = np.arange(n) / RATE
    spin = np.clip(tt / 1.2, 0, 1) * np.clip((6.8 - tt) / 0.6, 0, 1)
    f = 90 + 70 * np.clip(tt / 1.5, 0, 1)
    motor = (np.sin(2 * np.pi * np.cumsum(f) / RATE) + 0.4 * np.sin(4 * np.pi * np.cumsum(f) / RATE)) * 0.25
    fan = band(noise(rng, n), 300, 4000, 2) * 0.35
    x = (motor + fan) * spin
    for at in [1.6, 1.75, 3.2, 3.35, 4.8, 4.95]:
        L = secs(0.08)
        place(x, (resonator(L, 1400, 0.01) + band(noise(rng, L), 1000, 6000, 2) * env_exp(L, 0.01)) * 0.6, secs(at))
    L = secs(1.2)
    place(x, band(noise(rng, L), 1500, 7000, 2) * np.sin(np.linspace(0, np.pi, L)) * 0.35, secs(5.2))  # paper slide
    return norm(room(x, rng, rt=0.7, wet=0.25), 0.8)


def light_buzz():
    # a dying tube arcing: harsh 120 Hz buzz with crackle bursts
    rng = np.random.default_rng(71)
    n = secs(1.3)
    tt = np.arange(n) / RATE
    buzz = np.sign(np.sin(2 * np.pi * 120 * tt)) * 0.3 + 0.3 * np.sin(2 * np.pi * 240 * tt)
    crackle = band(noise(rng, n), 2000, 10000, 2) * (rng.random(n) < 0.004).astype(float) * 6
    gate = np.repeat((rng.random(n // secs(0.05) + 1) > 0.35).astype(float), secs(0.05))[:n]
    gate = signal.lfilter([0.02], [1, -0.98], gate)
    x = (band(buzz, 100, 6000, 2) + crackle) * gate * np.clip((1.3 - tt) / 0.1, 0, 1)
    return norm(x, 0.8)


def light_click():
    rng = np.random.default_rng(72)
    n = secs(0.3)
    x = resonator(n, 3200, 0.006) * 0.6 + band(noise(rng, n), 1500, 8000, 2) * env_exp(n, 0.004) \
        + 0.4 * resonator(n, 160, 0.03)
    return norm(room(x, rng, rt=0.8, wet=0.3), 0.7)


def flashlight_click():
    rng = np.random.default_rng(73)
    n = secs(0.12)
    x = band(noise(rng, n), 2000, 9000, 2) * env_exp(n, 0.003) + 0.5 * resonator(n, 2400, 0.004)
    return norm(x, 0.7)


def chair_creak():
    # an office chair's gas lift and springs creaking: stick-slip friction through a resonant body
    rng = np.random.default_rng(81)
    n = secs(1.4)
    tt = np.arange(n) / RATE
    rate = 38 + 25 * np.sin(np.pi * tt / 1.4) + rng.normal(0, 4, n).cumsum() / 400
    ph = np.cumsum(rate) / RATE
    pulses = (np.diff(np.floor(ph), prepend=0) > 0).astype(float)
    body = signal.lfilter(*signal.iirpeak(1150, 6, fs=RATE), pulses) + 0.6 * signal.lfilter(*signal.iirpeak(2300, 8, fs=RATE), pulses)
    x = body * np.sin(np.pi * tt / 1.4) ** 0.7
    return norm(room(x, rng, rt=0.7, wet=0.25), 0.7)


def step(kind, seed):
    rng = np.random.default_rng(seed)
    if kind == "carpet":  # muffled thud and a soft scuff of fibre
        n = secs(0.32)
        x = band(noise(rng, n), 60, 420, 2) * env_exp(n, 0.035, 0.006) * 1.4
        x += band(noise(rng, n), 1500, 6000, 2) * env_exp(n, 0.05, 0.02) * 0.08
        return norm(x, 0.8)
    if kind == "hard":  # heel click on polished stone or tile, a tight room ring
        n = secs(0.36)
        x = resonator(n, rng.uniform(150, 190), 0.025) * 0.6
        x += band(noise(rng, n), 1800, 9000, 2) * env_exp(n, 0.006, 0.0008) * 1.2
        x += resonator(n, rng.uniform(2500, 3400), 0.01) * 0.25
        return norm(room(x, rng, rt=0.9, wet=0.18), 0.85)
    if kind == "concrete":  # gritty: grains under the sole
        n = secs(0.4)
        x = resonator(n, rng.uniform(110, 140), 0.03) * 0.6 + band(noise(rng, n), 500, 3000, 2) * env_exp(n, 0.012, 0.002)
        grit = band(noise(rng, n), 3000, 10000, 2) * (rng.random(n) < 0.02) * env_exp(n, 0.07, 0.01) * 3
        return norm(room(x + grit, rng, rt=1.5, wet=0.3), 0.85)
    if kind == "metal":  # raised access floor panels in the server room
        n = secs(0.4)
        x = resonator(n, rng.uniform(320, 380), 0.05) * 0.5 + resonator(n, rng.uniform(900, 1100), 0.03) * 0.3
        x += band(noise(rng, n), 1500, 8000, 2) * env_exp(n, 0.006, 0.001)
        return norm(x, 0.85)
    raise ValueError(kind)


ONESHOTS = [
    ("thunder_near", lambda: thunder(1, crack=True, length=7.0)),
    ("thunder_mid", lambda: thunder(2, crack=False, length=7.5, distance=1.4)),
    ("thunder_far", lambda: thunder(3, crack=False, length=8.0, distance=2.2)),
    ("phone_ring", phone_ring),
    ("elevator_ding", elevator_ding),
    ("elevator_doors", elevator_doors),
    ("door_slam", door_slam),
    ("knock", knock_set),
    ("footsteps_far", footsteps_distant),
    ("printer", printer_run),
    ("light_buzz", light_buzz),
    ("light_click", light_click),
    ("flash_click", flashlight_click),
    ("chair_creak", chair_creak),
] + [(f"step_{k}_{i}", (lambda k=k, i=i: step(k, 100 + i * 7 + len(k)))) for k in ("carpet", "hard", "concrete", "metal") for i in (1, 2, 3)]

LOOPS = [
    ("ofc_rain", rain_loop),
    ("ofc_hvac", hvac_loop),
    ("ofc_server", server_loop),
    ("ofc_vending", vending_loop),
    ("ofc_hum", hum_loop),
]


def sfx_atlas():
    gap = secs(0.35)
    parts, regions, cur = [], {}, 0
    for name, make in ONESHOTS:
        x = make()
        parts += [x, np.zeros(gap)]
        regions[name] = [round(cur / RATE, 4), round((cur + len(x)) / RATE, 4)]
        cur += len(x) + gap
    return np.concatenate(parts), regions


def upload_and_record(name, path, label, regions=None):
    import manifest
    import upload
    from run import asset_owners, introspect  # noqa: F401 (run.py's key introspection)

    key = keyfile.find_key()
    if not key:
        print(f"{name}: wrote {path}; no key: upload it and record with run.py record-sound")
        return None
    sid = upload.upload_file(path, "Audio", f"{name} ({label})", key, introspect(key)["authorizedUserId"])
    entry = {"id": sid, "source": SOURCE, "license": "CC0 1.0", "remake": "python maps/office-floor-14/sounds.py --only " + name}
    if regions:
        entry["regions"] = regions
    manifest.update(PACK / "assets.json", lambda data: data.setdefault("sounds", {}).__setitem__(name, entry))
    print(f"{name}: uploaded {sid}")
    return sid


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-upload", action="store_true")
    ap.add_argument("--only", default="")
    a = ap.parse_args(argv)
    only = set(filter(None, a.only.split(",")))
    jobs = [(n, f, "generated loop", None) for n, f in LOOPS]
    jobs.append(("ofc_sfx", None, "generated one-shots", None))
    for name, make, label, _ in jobs:
        if only and name not in only:
            continue
        regions = None
        if make is None:
            x, regions = sfx_atlas()
        else:
            x = make()
        path = write(name, x)
        print(f"{name}: {len(x) / RATE:.1f} s -> {path}")
        if not a.no_upload:
            upload_and_record(name, path, label, regions)
        elif regions:
            print("  regions:", regions)


